import math#importing math module

n=int(input("Enter a number:"))#Taking the input from user


print(f"The square root of the numeber is{math.sqrt(n)}")#printing the square root of the number using the function sqrt
print(f"The logarithm root of the numeber is{math.log(n)}")#printing the log value  of the number using the function log
print(f"The sine of the number is {math.sin(n)}")#printing the sine value of the number using the function sin